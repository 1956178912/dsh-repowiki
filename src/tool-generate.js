                wikiDir: { type: 'string' },
                manifest: { type: 'string' },
                pages: { type: 'array', items: { type: 'string' } },
                cardsRead: { type: 'integer' },
                memoriesRead: { type: 'integer' },
                cardsTruncated: { type: 'integer' },
                memoriesTruncated: { type: 'integer' },
                failed: { type: 'array', items: { type: 'object', additionalProperties: false, properties: { slug: { type: 'string' }, reason: { type: 'string' } }, required: ['slug', 'reason'] } },
                orphaned: { type: 'array', items: { type: 'string' } },
                renamed: { type: 'array', items: { type: 'object', additionalProperties: false, properties: { from: { type: 'string' }, to: { type: 'string' } }, required: ['from', 'to'] } },
                aborted: { type: 'boolean' },
                attempts: { type: 'integer', description: 'Theme-synthesis attempts made (0 when skipped or module-only).' },
