/**
 * repowiki-generate 工具：把知识卡片集合凝练为 Wiki 页面。
 *
 * 数据流（方案 §6.3）：只读卡片集合（不重读源码）+ 技术栈 → 派发
 * spawn 子代理（outputSchema 约束页面结构）→ 渲染 Markdown（含
 * mermaid）→ 写 wiki/{locale}/。
 */

import {
  MAX_CARDS_IN_PROMPT, MAX_MEMORIES_IN_PROMPT,
} from './schema.js'
import {
  resolveAssetRoot, readIndex,
} from './assets.js'
import { wikiOutputSchema } from './card-schema.js'
import { generatePrompt } from './prompts.js'
import { renderWikiMarkdown } from './render.js'
import { readExistingCards, writeWikiPage } from './knowledge.js'
import { listMemory } from './memory.js'
import { runSubagent, getLocale } from './spawn.js'

/** 工具描述。 */
const DESCRIPTION = [
  'Synthesize knowledge cards into Wiki pages under .dsh-repowiki/wiki/<locale>/,',
  'grouped by theme (overview, core modules, data flow) with Markdown bodies and optional',
  'mermaid diagrams. Reads only the cards, not the source; requires cards generated by',
  'repowiki-extract first. Accepted session memory entries (repowiki-memory) are folded into',
  'the synthesis as project conventions and decisions.',
].join(' ')

/**
 * 构造 repowiki-generate 工具定义。
 * @param {object} ctx - 插件上下文。
 * @returns {object} ToolDefinition。
 */
export function repowikiGenerateTool(ctx) {
  return {
    name: 'repowiki-generate',
    description: DESCRIPTION,
    parameters: {
      root: {
        type: 'string',
        description: 'Optional project root. Defaults to the current directory; the asset root is found by walking up for .dsh-repowiki.',
      },
      locale: {
        type: 'string',
        enum: ['zh', 'en'],
        description: 'Wiki language. Defaults to the session environment language.',
      },
    },
    output: {
      schema: {
        type: 'object',
        additionalProperties: false,
        properties: {
          root: { type: 'string' },
          wikiDir: { type: 'string' },
          locale: { type: 'string' },
          pages: { type: 'array', items: { type: 'string' } },
          cardsRead: { type: 'integer' },
          memoriesRead: { type: 'integer' },
          durationMs: { type: 'integer' },
        },
        required: ['root', 'wikiDir', 'locale', 'pages', 'cardsRead', 'memoriesRead', 'durationMs'],
      },
      render: (_args, value) => [{
        type: 'text',
        text: value.pages.length > 0
          ? `Generated ${value.pages.length} wiki page(s) from ${value.cardsRead} card(s) and ${value.memoriesRead} accepted memory entrie(s) in ${value.durationMs}ms → ${value.wikiDir}: ${value.pages.join(', ')}`
          : value.hint ?? 'No pages generated.',
      }],
    },
    timeoutMs: 600_000,
    async execute(args, exec) {
      const fs = ctx.fs
      if (!fs) throw new Error('repowiki-generate requires the ctx.fs capability')
      const startedAt = Date.now()
      const locale = typeof args.locale === 'string' ? args.locale : getLocale(ctx)

      const startDir = typeof args.root === 'string' && args.root.trim() ? args.root : cwdOf(ctx)
      const { root } = await resolveAssetRoot(fs, startDir)
      const index = await readIndex(fs, root)

      const cardsMap = await readExistingCards(fs, root, locale)
      if (cardsMap.size === 0) {
        return {
          root, wikiDir: '', locale, pages: [], cardsRead: 0, memoriesRead: 0,
          durationMs: 0,
          hint: 'No knowledge cards found for this locale. Run repowiki-extract first (and repowiki-index before that).',
        }
      }

      // 组装卡片摘要喂给子代理（裁剪到 MAX_CARDS_IN_PROMPT）
      const cards = [...cardsMap.values()].slice(0, MAX_CARDS_IN_PROMPT).map(c => ({
        path: c.meta.path,
        title: c.meta.title,
        summary: c.meta.summary ?? '',
        keySymbols: Array.isArray(c.meta.keySymbols) ? c.meta.keySymbols : [],
        tags: Array.isArray(c.meta.tags) ? c.meta.tags : [],
      }))
      const stack = index
        ? { projectName: index.stack?.projectName, technologies: index.stack?.technologies ?? [] }
        : { technologies: [] }

      // 已采信的会话记忆（Phase 4 消费侧）：标题 + 正文首行，作为项目
      // 约定/决策上下文注入生成 prompt
      const memories = await listMemory(fs, root, locale, 'accepted', true)
      const memorySummaries = memories.slice(0, MAX_MEMORIES_IN_PROMPT).map(m => ({
        title: m.title,
        summary: (m.body ?? '').split('\n')[0].slice(0, 200),
      }))

      const prompt = generatePrompt(cards, stack, locale, memorySummaries)
      const result = await runSubagent(ctx, {
        prompt,
        outputSchema: wikiOutputSchema(),
        agent: exec.agent,
        signal: exec.signal,
        label: 'repowiki-generate',
        name: 'rw-generate-1',
      })
      const pages = result?.structured?.pages
      if (!Array.isArray(pages) || pages.length === 0) {
        return {
          root, wikiDir: '', locale, pages: [], cardsRead: cards.length,
          memoriesRead: memorySummaries.length,
          durationMs: Date.now() - startedAt,
          hint: result?.diagnostic || `Wiki synthesis ended (${result?.stopReason ?? 'unknown'}) without pages.`,
        }
      }

      const written = []
      for (const page of pages) {
        if (typeof page.slug !== 'string' || !page.slug) continue
        const md = renderWikiMarkdown(page, { locale, generatedAt: new Date().toISOString() })
        await writeWikiPage(fs, root, page.slug, locale, md)
        written.push(page.slug)
      }
      return {
        root,
        wikiDir: `${root}/.dsh-repowiki/wiki/${locale}`,
        locale,
        pages: written,
        cardsRead: cards.length,
        memoriesRead: memorySummaries.length,
        durationMs: Date.now() - startedAt,
      }
    },
    presentCall: (args) => ({
      card: 'generic',
      title: 'Generate wiki pages',
      kind: 'execute',
      rawInput: { root: args.root ?? '(current)', locale: args.locale ?? 'auto' },
    }),
  }
}

/** 取当前工作目录。 */
function cwdOf(ctx) {
  const wd = ctx.workingDirectory
  if (wd && typeof wd.get === 'function') {
    try { return wd.get() } catch { /* 降级到 process.cwd */ }
  }
  return process.cwd()
}
