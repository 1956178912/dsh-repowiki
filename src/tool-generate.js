/** 单条引用允许的最大长度（路径 + 行号）。 */
const MAX_SOURCE_LENGTH = 240

/** 每节引用的上限（防止异常输出撑大页面）。 */
const MAX_SOURCES_PER_SECTION = 12

/** 引用形态：相对路径（Unicode 字母数字与 ._/-）+ 可选 #Lx-Ly 行号范围。 */
const SOURCE_PATTERN = /^([\p{L}\p{N}._/-]+)(#L\d+(?:-L\d+)?)?$/u

/**
 * 净化 LLM 返回的章节引用：只保留白名单内的相对路径与合法的行号范围。
 * @param {unknown} value - 子代理返回的 sources 字段。
 * @param {Set<string>} knownPaths - 允许引用的文件路径集合。
 * @returns {string[]} 净化后的引用（去重、有界）。
 */
export function sanitizeSources(value, knownPaths) {
  if (!Array.isArray(value)) return []
  const out = []
  const seen = new Set()
  for (const raw of value) {
    if (typeof raw !== 'string') continue
    const candidate = raw.trim().replace(/^`+|`+$/g, '')
    if (candidate.length === 0 || candidate.length > MAX_SOURCE_LENGTH) continue
    const match = SOURCE_PATTERN.exec(candidate)
    if (!match) continue
    const [, path, range = ''] = match
    if (!knownPaths.has(path)) continue
    const source = `${path}${range}`
    if (seen.has(source)) continue
    seen.add(source)
    out.push(source)
    if (out.length >= MAX_SOURCES_PER_SECTION) break
  }
  return out
}

/**
 * 渲染未覆盖引用的原因摘要。
 * @param {{unreadable?:number, range?:number, cap?:number, unknown?:number}|undefined} reasons
 *   原因计数。
 * @returns {string} 例如 `1 unreadable, 2 invalid range`；无计数时为空。
 */
function citationReasonText(reasons) {
  if (!reasons) return ''
  const parts = []
  if (reasons.unreadable > 0) parts.push(`${reasons.unreadable} unreadable`)
  if (reasons.range > 0) parts.push(`${reasons.range} invalid range`)
  if (reasons.cap > 0) parts.push(`${reasons.cap} over read cap`)
  if (reasons.unknown > 0) parts.push(`${reasons.unknown} unknown`)
  return parts.join(', ')
}

/**
 * 跳过合成时的引用指纹状态：完整覆盖、部分未覆盖或旧清单。
 * @param {{citationCoverage?:{total?:number, tracked?:number, untracked?:number,
 *   reasons?:object}}} value - 工具输出。
 * @returns {string} 单行状态。
 */
function citationStateForSkip(value) {
  const coverage = value.citationCoverage
  if (!coverage || !(coverage.total > 0)) return 'manifest has no citation digests'
  if (coverage.untracked > 0) {
    const detail = citationReasonText(coverage.reasons)
    return `${coverage.tracked}/${coverage.total} cited source(s) verified; ${coverage.untracked} have no content digest${detail ? ` (${detail})` : ''}`
  }
  return 'cited sources verified'
}

/**
 * 未覆盖引用的指纹提示；完整覆盖时返回空字符串。
 * @param {{total?:number, tracked?:number, untracked?:number, reasons?:object}|undefined} coverage
 *   引用指纹覆盖率。
 * @returns {string} 提示文本。
 */
function untrackedCitationNote(coverage) {
  if (!coverage || !(coverage.total > 0) || !(coverage.untracked > 0)) return ''
  const detail = citationReasonText(coverage.reasons)
  return `${coverage.tracked}/${coverage.total} cited source(s) have content digests; ${coverage.untracked} untracked${detail ? ` (${detail})` : ' (reason unknown)'}; drift checks skip them.`
}

